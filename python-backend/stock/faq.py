_TOPIC_INDEX: dict[str, dict[str, Any]] = {t["id"]: t for t in _TOPICS}


def list_topics() -> list[str]:
    return [t["title"] for t in _TOPICS]


def _score(topic: dict[str, Any], question: str) -> int:
    q = question.lower()
    score = 0
    for kw in topic["keywords"]:
        if kw.lower() in q:
            # 关键词越长越具体，权重越高
            score += max(1, len(kw) // 2)
    return score


def lookup(question: str) -> str:
    """按关键词匹配最相关的一条规则；匹配不到时返回可问的主题列表。"""
    text = (question or "").strip()
    if not text:
        return "请问你想了解哪条 A股交易规则？可问：" + "、".join(list_topics())

    scored = sorted(
        ((_score(t, text), t) for t in _TOPICS), key=lambda pair: pair[0], reverse=True
    )
    best_score, best = scored[0]
    if best_score <= 0:
        return (
            f"规则库里暂时没有和「{text}」直接匹配的条目。目前收录："
            + "、".join(list_topics())
            + "。可以换个说法再问一次。"
        )
    return f"【{best['title']}】\n{best['answer']}\n\n{DISCLAIMER}"
